CREATE INDEX IDX_LICENCAS_USUARIO ON LICENCAS(USUARIO_ID, STATUS_ATIVO);
CREATE INDEX IDX_COMPROVANTES_USUARIO ON COMPROVANTES_PAGAMENTO(USUARIO_ID);

